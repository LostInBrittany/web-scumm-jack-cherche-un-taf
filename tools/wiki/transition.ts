// `npm run wiki -- transition` (4.5.0 "Wiki", docs/dev/PLAN-4.5-WIKI.md §4.5.4 and §4.5.7, step 2; ADR 0030): the
// transition pages C2 writes in place of `docs/en/*.md` and `docs/fr/*.md`. Each keeps every heading of the old page
// at its level, in its order and with its text (escaped, so GitHub computes the same anchor, `-1` and `-2` for repeated
// ones), and every explicit `<a id>` of the L2 inventory (`wiki/coverage.json`). Under each heading, the section's new
// places in this release's own documentation, through its version alias `<Pages>/docs/<version>/<lang>/<id>.html#<section>`
// (so a later doc revision of that version is followed; never the wiki nor `latest`), the version read from
// package.json; and a fallback link that always works, to the
// complete 4.4.0 page at `blob/v4.4.0/docs/<lang>/<FILE>.md#<anchor>`. A section dropped says why. The release pull
// request regenerates them; a test checks their version is package.json's. Written by C2, not before.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { BOOTSTRAP_LATEST } from './build';
import { siteDocs } from './site';
import type { Coverage, CoverageRow } from './coverage';
import type { Manifest } from './manifest';

const REPO_URL = 'https://github.com/Quest-n-Click/quest-n-click';
/** The first line of a transition page: generated, and for which version. */
const TRANSITION_MARKER = (version: string) =>
  `<!-- quest-n-click transition page: version ${version}; generated by npm run wiki -- transition, do not edit -->`;
export const TRANSITION_LINE = /^<!-- quest-n-click transition page: version (\S+);/;

/** A heading's text written back so it renders as it did: Markdown's punctuation escaped, the slug unchanged. */
const escapeHeading = (text: string) =>
  text
    .replace(/[\\`*_[\]<>#|!()&~{}^]/g, (c) => `\\${c}`)
    // A space at an end (an old heading that ended on an HTML tag, `on <date>`) is kept by an empty comment after it,
    // which renders nothing: Markdown trims a heading, and the slug would lose its last `-`.
    .replace(/\s+$/, (m) => `${m}<!-- -->`);

const WORDS = {
  en: {
    notice: (v: string, old: string) =>
      `This page moved to the quest'n'click documentation. Each section below links to its new place in the latest documentation, on the project's website (written for version ${v}); the complete ${BOOTSTRAP_LATEST} page stays readable at [${old}](${old}).`,
    now: 'Now in',
    dropped: 'Removed',
    old: `The ${BOOTSTRAP_LATEST} text`,
    planned: 'not placed yet',
  },
  fr: {
    notice: (v: string, old: string) =>
      `Cette page a déménagé dans la documentation de quest'n'click. Chaque section ci-dessous mène à sa nouvelle place dans la dernière documentation, sur le site du projet (écrite pour la version ${v}) ; la page complète de la ${BOOTSTRAP_LATEST} reste lisible sur [${old}](${old}).`,
    now: 'Désormais dans',
    dropped: 'Retiré',
    old: `Le texte de la ${BOOTSTRAP_LATEST}`,
    planned: 'pas encore placée',
  },
} as const;

/** The transition page of one old file (`docs/<lang>/<FILE>.md`), from its rows of the matrix, in their order. */
function transitionPage(file: string, rows: readonly CoverageRow[], manifest: Manifest, version: string): string {
  const lang = /^docs\/fr\//.test(file) ? 'fr' : 'en';
  const w = WORDS[lang];
  const old = `${REPO_URL}/blob/v${BOOTSTRAP_LATEST}/${file}`;
  const title = (id: string) => manifest.pages.find((p) => p.id === id)?.title[lang] ?? id;
  const links = (r: CoverageRow) => {
    const back = `[${w.old}](${old}${r.anchor ? `#${r.anchor}` : ''})`;
    if (r.decision === 'drop') return `${w.dropped}${lang === 'fr' ? ' :' : ':'} ${r.reason ?? ''} · ${back}`;
    const to = r.destinations.map((d) => {
      const [id, section] = d.split('#') as [string, string | undefined];
      return `[${title(id)}${section ? ` › ${section}` : ''}](${siteDocs(lang, id, section)})`;
    });
    return `${w.now}${lang === 'fr' ? ' :' : ':'} ${to.length ? to.join(' · ') : w.planned} · ${back}`;
  };
  const out = [TRANSITION_MARKER(version), ''];
  let noticed = false;
  const notice = () => {
    if (noticed) return;
    noticed = true;
    out.push(`> ${w.notice(version, old)}`, '');
  };
  for (const r of rows) {
    if (r.level === 0) {
      notice();
      out.push(links(r), '');
      for (const a of r.anchors) out.push(`<a id="${a}"></a>`, '');
      continue;
    }
    out.push(`${'#'.repeat(r.level)} ${escapeHeading(r.heading)}`, '');
    notice();
    out.push(links(r), '');
    // An explicit anchor stays in its section, at its end: where one usually stands, right before the next heading.
    for (const a of r.anchors) out.push(`<a id="${a}"></a>`, '');
  }
  if (!noticed) notice();
  return `${out.join('\n').trimEnd()}\n`;
}

/** Every transition page of the matrix's `docs/en` and `docs/fr` files, by path; written under `root` when asked. */
export function transitionPages(coverage: Coverage, manifest: Manifest, version: string): Map<string, string> {
  const byFile = new Map<string, CoverageRow[]>();
  for (const r of coverage.rows)
    if (/^docs\/(en|fr)\/[^/]+\.md$/.test(r.file)) byFile.set(r.file, [...(byFile.get(r.file) ?? []), r]);
  return new Map(
    [...byFile]
      .sort(([a], [b]) => (a < b ? -1 : 1))
      .map(([file, rows]) => [file, transitionPage(file, rows, manifest, version)]),
  );
}

export function writeTransitionPages(root: string, pages: Map<string, string>): string[] {
  for (const [file, text] of pages) {
    const path = resolve(root, file);
    if (!existsSync(dirname(path))) mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  return [...pages.keys()];
}
